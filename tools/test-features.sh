#!/usr/bin/env bash
# Roda `devcontainer features test` para as features pedidas (todas, sem argumento).
#
# ANTES da primeira publicacao, o `installsAfter: ghcr.io/huldlabs/endurance/<x>` nao
# resolve (o CLI busca o manifesto no registry e falha). Com ENDURANCE_UNPUBLISHED=1 o teste
# roda numa COPIA sem essas referencias; a ordem vem do `overrideFeatureInstallOrder` dos
# scenarios. Depois da publicacao, rode sem a variavel: testa o arquivo como o consumidor ve.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
CLI="@devcontainers/cli@0.89.0"
feats=("$@"); [ ${#feats[@]} -gt 0 ] || mapfile -t feats < <(ls "$root/test")

dir="$root"
if [ "${ENDURANCE_UNPUBLISHED:-0}" = "1" ]; then
  dir="$(mktemp -d)"; trap 'rm -rf "$dir"' EXIT
  cp -r "$root/src" "$root/test" "$dir/"
  for j in "$dir"/src/*/devcontainer-feature.json; do
    python3 - "$j" <<'PY'
import json,sys
p=sys.argv[1]; d=json.load(open(p))
d["installsAfter"]=[x for x in d.get("installsAfter",[]) if not x.startswith("ghcr.io/huldlabs/")]
json.dump(d,open(p,"w"),indent=2)
PY
  done
fi

rc=0
for f in "${feats[@]}"; do
  echo "== $f"
  npx -y "$CLI" features test -p "$dir" -f "$f" --skip-autogenerated --skip-duplicated || rc=1
done
exit $rc
